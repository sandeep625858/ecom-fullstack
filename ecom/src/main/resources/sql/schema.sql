CREATE TABLE products
(
    product_id  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR2(250) NOT NULL,
    description VARCHAR2(500) NOT NULL,
    price       NUMBER(10, 2) NOT NULL,
    popularity  NUMBER(10) NOT NULL,
    image_url   VARCHAR2(500),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by  VARCHAR2(100) NOT NULL,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR2(100)
);


CREATE TABLE contacts
(
    contact_id    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    email         VARCHAR2(100) NOT NULL,
    mobile_number VARCHAR2(15) NOT NULL,
    message       VARCHAR2(500) NOT NULL,
    status        VARCHAR2(50) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by    VARCHAR2(100) NOT NULL,
    updated_at    TIMESTAMP,
    updated_by    VARCHAR2(100)
);


CREATE TABLE customers
(
    customer_id   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    email         VARCHAR2(100) NOT NULL,
    mobile_number VARCHAR2(15) NOT NULL,
    password_hash VARCHAR2(500) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by    VARCHAR2(100) NOT NULL,
    updated_at    TIMESTAMP,
    updated_by    VARCHAR2(100),

    CONSTRAINT unique_customer_email
        UNIQUE (email),

    CONSTRAINT unique_customer_mobile
        UNIQUE (mobile_number)
);


CREATE TABLE address
(
    address_id    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER(19) NOT NULL,
    street        VARCHAR2(150) NOT NULL,
    city          VARCHAR2(100) NOT NULL,
    state         VARCHAR2(100) NOT NULL,
    postal_code   VARCHAR2(20) NOT NULL,
    country       VARCHAR2(100) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by    VARCHAR2(100) NOT NULL,
    updated_at    TIMESTAMP,
    updated_by    VARCHAR2(100),

    CONSTRAINT unique_address_customer
        UNIQUE (customer_id),

    CONSTRAINT fk_address_customer
        FOREIGN KEY (customer_id)
            REFERENCES customers(customer_id)
            ON DELETE CASCADE
);

CREATE TABLE roles (
                       role_id     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       customer_id NUMBER(19) NOT NULL,
                       name        VARCHAR2(50) NOT NULL,
                       created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                       created_by  VARCHAR2(20) NOT NULL,
                       updated_at  TIMESTAMP,
                       updated_by  VARCHAR2(20),

                       CONSTRAINT fk_roles_customer
                           FOREIGN KEY (customer_id)
                               REFERENCES customers(customer_id)
                               ON DELETE CASCADE
);

CREATE TABLE roles
(
    role_id    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(50) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by VARCHAR2(100) NOT NULL,
    updated_at TIMESTAMP,
    updated_by VARCHAR2(100),

    CONSTRAINT unique_role_name UNIQUE (name)
);


CREATE TABLE customer_roles
(
    customer_id NUMBER(19) NOT NULL,
    role_id     NUMBER(19) NOT NULL,

    CONSTRAINT pk_customer_roles
        PRIMARY KEY (customer_id, role_id),

    CONSTRAINT fk_customer_roles_customer
        FOREIGN KEY (customer_id)
            REFERENCES customers(customer_id)
            ON DELETE CASCADE,

    CONSTRAINT fk_customer_roles_role
        FOREIGN KEY (role_id)
            REFERENCES roles(role_id)
            ON DELETE CASCADE
);


